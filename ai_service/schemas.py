from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

# Sequence 1: Summarize
class SummarizeRequest(BaseModel):
    title: str = Field(..., description="Grievance title")
    description: str = Field(..., description="Full grievance description")

class SummarizeResponse(BaseModel):
    summary: str
    key_points: List[str]
    word_count_original: int
    word_count_summary: int
    model: str = "gemini-3.5-flash"
    disclaimer: str = "Advisory AI summary. Does not modify official grievance record."

# Sequence 2: Suggest Categories and Departments
class ClassificationRequest(BaseModel):
    title: str
    description: str
    available_categories: Optional[List[str]] = None
    available_departments: Optional[List[str]] = None

class ClassificationResponse(BaseModel):
    suggested_category: str
    suggested_department: str
    confidence: float
    reasoning: str
    model: str = "gemini-3.5-flash"

# Sequence 3: Identify Missing Information
class MissingInfoRequest(BaseModel):
    title: str
    description: str
    category: Optional[str] = None

class MissingInfoResponse(BaseModel):
    is_information_complete: bool
    missing_information: List[str]
    suggested_questions_for_student: List[str]
    completeness_score: float
    model: str = "gemini-3.5-flash"

# Sequence 4: Generate Officer Follow-up Suggestions
class OfficerSuggestionsRequest(BaseModel):
    title: str
    description: str
    category: str
    department: Optional[str] = None
    current_status: Optional[str] = "Submitted"

class OfficerSuggestionsResponse(BaseModel):
    recommended_actions: List[str]
    recommended_priority: str
    suggested_sla_hours: int
    recommended_next_status: str
    suggested_student_query: Optional[str] = None
    model: str = "gemini-3.5-flash"
    checkpoint_notice: str = "Suggestions are non-binding recommendations. Official status change requires human officer action."

# Comprehensive Single Grievance Analysis (Sequences 1-4 combined)
class AnalyzeGrievanceRequest(BaseModel):
    title: str
    description: str
    category: Optional[str] = None
    department: Optional[str] = None
    current_status: Optional[str] = "Submitted"
    available_categories: Optional[List[str]] = None
    available_departments: Optional[List[str]] = None

class AnalyzeGrievanceResponse(BaseModel):
    summary: str
    key_points: List[str]
    suggested_category: str
    suggested_department: str
    classification_confidence: float
    classification_reasoning: str
    is_information_complete: bool
    missing_information: List[str]
    recommended_officer_actions: List[str]
    recommended_priority: str
    suggested_sla_hours: int
    suggested_student_query: Optional[str] = None
    model: str = "gemini-3.5-flash"
    disclaimer: str = "AI suggestions are advisory only and must be reviewed by an authorized human officer. AI does not alter official status."

# Sequence 5: Identify Trends in Aggregate Grievance Data
class GrievanceRecordItem(BaseModel):
    ticket_id: str
    title: str
    category: str
    department_name: Optional[str] = "General"
    status: str
    priority: Optional[str] = "Medium"
    created_at: Optional[str] = None

class TrendsRequest(BaseModel):
    grievances: List[GrievanceRecordItem]
    timeframe: Optional[str] = "Past 30 Days"

class TrendCluster(BaseModel):
    issue_topic: str
    affected_departments: List[str]
    grievance_count: int
    severity: str
    summary_insight: str

class TrendsResponse(BaseModel):
    total_analyzed: int
    top_recurring_issues: List[TrendCluster]
    hotspot_departments: List[Dict[str, Any]]
    emerging_patterns: List[str]
    actionable_recommendations: List[str]
    model: str = "gemini-3.5-flash"
    disclaimer: str = "Institutional trend analysis generated by Gemini. Advisory intelligence for administrators."

